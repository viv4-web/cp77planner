#!/usr/bin/env python3
"""Generate data/ripperdoc/layout.json and src/styles/ripperdoc-tokens.css from the ripperdoc UI export (Python 3 stdlib only).

  tools/ripperdoc_layout.py

Reads ~/work/cyber-art/raw/ui (read only; raw game content, never committed) and writes only numbers: positions on a 1920x1080 stage
(the spec's 3840x2160 design grid halved), zoom/fade timings of the zone sequences, and style tokens as CSS custom properties.
Spec: docs/RIPPERDOC-SPEC.md and docs/RIPPERDOC-ANIMATIONS.md. Re-run after a game patch; the output is deterministic.
"""
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ripperdoc_data as rd  # noqa: E402
import ripperdoc_render as rr  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
H = 0.5          # design grid -> 1920x1080 stage
# zone key (widget name stem), woman/man sequence stem, our slot group key, slot panel anchor widget, hover sprite stem
ZONES = [
    ("frontal_cortex", "frontalCortex", "FrontalCortex", "frontalAnchor", "frontal_cortex"),
    ("ocular", "ocular", "Face", "OcularNew", "okular"),
    ("circulatory", "circlatory", "Circulatory", "cardiovascularAnchor", "circulatory"),
    ("hands", "hands", "Hands", "handsAnchorNew", "hands"),
    ("arms", "arms", "Arms", "armsAnchor", "arms"),
    ("legs", "legs", "Legs", "legsAnchor", "legs"),
    ("nervous", "nervous", "NervousSystem", "nervousAnchor", "nervous"),
    ("integumentary", "integumentary", "Integumentary", "integumentaryAnchor", "integumentary"),
    ("operating", "operating", "OperatingSystem", "systemAnchor", "operating"),
    ("skeleton", "skeleton", "Skeleton", "skeletonAnchor", "skeleton"),
]
# the legacy Immune zone has no slot group in our data and is left out


def r1(v):
    return round(v, 2) if isinstance(v, float) else v


def chain(root, names_or_path):
    """Rect (design px) of the node at the given child-index path, composed through the Paperdoll hierarchy (no render transforms)."""
    pr = (0, 0, 3840, 2160)
    n = root
    rect = (0, 0, n["size"][0], n["size"][1])
    pr = rect
    for i in names_or_path:
        n = n["children"][i]
        png = rr.part_png(n.get("atlas"), n.get("part")) if n["type"] == "inkImageWidget" else None
        nat = rr.png_wh(png) if png else None
        rect = rr.place(n, pr, nat)
        pr = rect
    return n, rect


def own(n, rect):
    """Apply the widget's own render transform (scale about its pivot)."""
    sx, sy = n["scale"]
    cx, cy = rect[0] + rect[2] * n["pivot"][0], rect[1] + rect[3] * n["pivot"][1]
    return (cx - (cx - rect[0]) * sx, cy - (cy - rect[1]) * sy, rect[2] * sx, rect[3] * sy)


def stage(rect):
    return [r1(v * H) for v in rect]


def pt(v):
    return [r1(v[0] * H), r1(v[1] * H)]


def interps(seq, root, path):
    """Interpolators of a sequence targeting `path`, translations halved to stage px."""
    out = []
    for d in seq["defs"]:
        if d["path"] != path:
            continue
        for i in d["interpolators"]:
            f, t = i["from"], i["to"]
            if i["kind"] == "Translation":
                f, t = pt(f), pt(t)
            elif isinstance(f, list):
                f, t = [r1(x) for x in f], [r1(x) for x in t]
            out.append({"kind": i["kind"], "from": r1(f), "to": r1(t), "dur": i["duration"], "delay": i["delay"], "type": i["type"], "mode": i["mode"]})
    return out


def video_window(seq, root, path):
    for d in seq["defs"]:
        if d["path"] == path:
            for i in d["interpolators"]:
                if i["kind"] == "Video":
                    return {"from": r1(i["from"]), "to": r1(i["to"]), "dur": i["duration"]}
    return None


def find_path(root, name):
    found = []

    def go(n, d):
        if n["name"] == name:
            found.append(n["path"])
    rd.walk(root, go)
    return found[0] if found else None


def build_layout():
    lib = rd.widget_library(f"{rd.RIPPER}/ripperdoc.inkwidget.json")
    root = lib["Root"]["root"]
    seqs = {s["name"]: s for s in rd.animations(f"{rd.RIPPER}/ripperdoc_animations.inkanim.json")}
    tab_path = find_path(root, "Paperdoll_default_tab")
    wrap_path = find_path(root, "paperDollWrapper")
    _, wrap = chain(root, wrap_path)
    _, tab_rect = chain(root, tab_path)
    layout = {"_note": "Numbers from the game's ripperdoc UI (design grid 3840x2160 halved to a 1920x1080 stage). Generated by tools/ripperdoc_layout.py.",
              "stage": [1920, 1080], "tabPivot": pt((tab_rect[0] + tab_rect[2] / 2, tab_rect[1] + tab_rect[3] / 2)), "genders": {}, "zones": []}
    for gi, (gender, loop, seqpre) in enumerate((("woman", "female_body_loop", ""), ("man", "male_body_loop", "M_"))):
        g = {"loop": loop, "zones": {}}
        # idle body loop: the video widget inside the default tab whose clip is the body loop
        body = None

        def pick(n, d):
            nonlocal body
            if n.get("video", "").endswith(f"{loop}.bk2"):
                body = n
        rd.walk(root, pick)
        bn, brect = chain(root, body["path"])
        g["body"] = {"rect": stage(own(bn, brect))}
        for key, stem, group, anchor, hover in ZONES:
            hpath = find_path(root, f"paperdoll_{gender}_{hover}")
            cpath = find_path(root, f"paperdoll_{key}_canvas")
            vpath = find_path(root, f"{gender}_paperdoll_{key}")
            hn, hrect = chain(root, hpath)
            cn, crect = chain(root, cpath)
            vn, vrect = chain(root, vpath)
            intro, outro = seqs[f"{seqpre}{stem}_intro"], seqs[f"{seqpre}{stem}_outro"]
            g["zones"][key] = {
                "sprite": {"part": hn["part"], "rect": stage(own(hn, hrect))},
                "clip": {"name": Path(vn["video"]).stem, "rect": stage(own(vn, vrect)), "native": vn["size"]},
                "canvasPivot": pt((crect[0] + crect[2] / 2, crect[1] + crect[3] / 2)),
                "intro": {"tab": interps(intro, root, tab_path), "canvas": interps(intro, root, cpath), "clip": video_window(intro, root, vpath)},
                "outro": {"tab": interps(outro, root, tab_path), "canvas": interps(outro, root, cpath), "clip": video_window(outro, root, vpath)},
            }
        layout["genders"][gender] = g
    for key, stem, group, anchor, hover in ZONES:
        n, rect = chain(root, find_path(root, anchor))
        layout["zones"].append({"key": key, "group": group, "anchor": pt((rect[0], rect[1]))})
    # meters (stage px; design px halved): positions of the pieces inside capacity_bar / armor_bar
    cap = root["children"][3]
    arm = root["children"][4]
    _, crect = chain(root, cap["path"])
    _, arect = chain(root, arm["path"])
    layout["meters"] = {"capacity": {"origin": pt(crect[:2]), "bgOffset": pt((-59, -18)), "labelX": r1(286 * H), "iconOffset": pt((63, -28))},
                        "armor": {"origin": pt(arect[:2]), "bgOffset": pt((-40, -17)), "labelX": r1(-130 * H), "iconOffset": pt((79, -30))}}
    _, inv = chain(root, find_path(root, "cyberwareContainer"))
    layout["inventory"] = {"origin": pt(inv[:2]), "grid": [r1(906 * H), r1(1010 * H)], "cell": [112, 101], "filter": [r1(888 * H), 50]}
    return layout


def css_tokens():
    main = rd.styles(f"{rd.COMMON}/main_colors.inkstyle.json")
    sets = [rd.styles(f"{rd.COMMON}/rarity_menus.inkstyle.json"), rd.styles(f"{rd.RIPPER}/ripperdoc_poor.inkstyle.json"),
            rd.styles(f"{rd.COMMON}/components/slots_style.inkstyle.json")]
    allt = dict(main)
    for s in sets:
        allt.update(s)

    def resolve(v, depth=0):
        if isinstance(v, tuple) and v and v[0] == "ref" and depth < 8:
            tgt = allt.get(v[1], {}).get("Default")
            return resolve(tgt, depth + 1) if tgt is not None else None
        return v

    lines = ["/* Generated by tools/ripperdoc_layout.py from the ripperdoc style tokens. Do not edit. Colors are clamped to sRGB; the excess of HDR",
             "   (emissive) colors is a separate -glow shadow (see docs/RIPPERDOC-SPEC.md). Names: --t-<Group>-<property>[-<State>]. */", ":root{"]
    for name in sorted(allt):
        for state in sorted(allt[name]):
            val = resolve(allt[name][state])
            if val is None:
                continue
            var = "--t-" + name.replace(".", "-") + ("" if state == "Default" else f"-{state}")
            if isinstance(val, tuple) and len(val) == 4 and all(isinstance(x, (int, float)) for x in val):
                lines.append(f"  {var}:{rd.hexcolor(val)};")
                over = max(val[:3])
                if over > 1.0001:
                    a = min(0.7, (over - 1) * 1.5)
                    c = [min(255, round(x / over * 255)) for x in val[:3]]
                    lines.append(f"  {var}-glow:0 0 6px rgba({c[0]},{c[1]},{c[2]},{a:.2f});")
            elif isinstance(val, (int, float)):
                lines.append(f"  {var}:{round(val, 4)};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    layout = build_layout()
    out = ROOT / "data" / "ripperdoc"
    out.mkdir(parents=True, exist_ok=True)
    (out / "layout.json").write_text(json.dumps(layout, indent=1) + "\n")
    (ROOT / "src" / "styles" / "ripperdoc-tokens.css").write_text(css_tokens())
    print(f"layout: {len(layout['zones'])} zones x 2 genders, tokens: {sum(1 for l in css_tokens().splitlines() if l.startswith('  --t-'))}")


if __name__ == "__main__":
    main()
