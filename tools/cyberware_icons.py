#!/usr/bin/env python3
"""Map every cyberware record to a cut item icon: data/cyberware.json + ~/work/cyber-art/out/ui/atlas-index.json -> data/ripperdoc/icons.json.

  tools/cyberware_icons.py [--index FILE] [--out FILE]

A record's `icon` (the game's iconPart) is looked up as a part name in the item icon atlases cut by tools/atlas_cut.py. Records with no iconPart
carry `iconName` instead (the 15 Operating System decks); that name is looked up the same way, then in FALLBACK. The output holds only art keys
(atlas/part names), never game art. Prints the misses; exits 1 when a record has no icon at all. Deterministic.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = Path.home() / "work" / "cyber-art" / "out" / "ui" / "atlas-index.json"
ATLASES = ("item_icons", "inventory4_atlas")  # item_icons0..23 are matched by prefix
# iconName values with no part in any exported atlas -> generic icon of the same kind (reported as an approximation)
FALLBACK = {"militech_paraline": "icon_cyberdeck"}


def find(parts_by_name, name):
    hits = [a for a in parts_by_name.get(name, []) if a.startswith(ATLASES)]
    return f"{hits[0]}/{name}" if hits else None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--index", default=str(INDEX))
    ap.add_argument("--out", default=str(ROOT / "data" / "ripperdoc" / "icons.json"))
    a = ap.parse_args(argv)
    idx = json.loads(Path(a.index).read_text())["atlases"]
    by_name = {}
    for atlas, v in sorted(idx.items()):
        for part in v["parts"]:
            by_name.setdefault(part, []).append(atlas)
    data = json.loads((ROOT / "data" / "cyberware.json").read_text())["implants"]
    keys = {}
    for i in data:
        k = i.get("icon") or i.get("iconName")
        if k:
            keys.setdefault(k, []).append(i["id"])
        else:
            keys.setdefault(None, []).append(i["id"])
    mapping, approx, miss = {}, {}, []
    for k in sorted(k for k in keys if k):
        hit = find(by_name, k)
        if not hit and k in FALLBACK:
            hit = find(by_name, FALLBACK[k])
            if hit:
                approx[k] = hit
        if hit:
            mapping[k] = hit
        else:
            miss.append(k)
    out = {"_note": "Generated by tools/cyberware_icons.py: cyberware icon key (iconPart, or iconName when there is none) -> atlas/part of the cut item icons.",
           "map": mapping, "approximated": approx, "missing": miss, "noKey": sorted(keys.get(None, []))}
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    n_rec = sum(len(v) for k, v in keys.items() if k)
    print(f"{len(data)} records, {len(mapping)} icon keys mapped to atlas parts; records covered: "
          f"{sum(len(keys[k]) for k in mapping)}/{len(data)}")
    for k, v in approx.items():
        print(f"approximated: {k} ({len(keys[k])} records) -> {v}")
    for k in miss:
        print(f"MISS: {k} ({len(keys[k])} records)")
    if keys.get(None):
        print(f"NO KEY: {len(keys[None])} records")
    return 1 if miss or keys.get(None) else 0


if __name__ == "__main__":
    sys.exit(main())
