#!/usr/bin/env python3
"""Find where each paperdoll zone clip can loop: data/ripperdoc/loops.json (Python 3 stdlib + ffmpeg).

  tools/loop_points.py [--paperdoll DIR] [--out FILE] [--report]

Decodes every clip (the small WebM, alpha included, at 96 px wide) and compares the last frame with every earlier frame. The loop start is
the earlier frame that the last frame is closest to, searched only in the second half of the clip ("sensible frame onward": the first part
is the intro). When the last frame is already as close to frame 0 as to anything else (a clip that loops as a whole) the start is 0 and the
page uses the video's native loop. The result is numbers only: per clip {frames, fps, loopStart, seam, firstSeam, motion}; `seam` is the
mean absolute difference between the last frame and the frame before the loop start (lower is smoother), `motion` the median difference
between neighbouring frames (what a smooth loop looks like). Deterministic.
"""
import argparse
import json
import statistics
import subprocess
import sys
from pathlib import Path

HOME = Path.home() / "work" / "cyber-art"
ROOT = Path(__file__).resolve().parent.parent
W = 96


def frames(path: Path):
    """[bytes] RGBA frames of a VP9+alpha WebM at W px wide (libvpx decoder: ffmpeg's native vp9 drops alpha)."""
    info = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", str(path)],
                          capture_output=True, text=True, check=True).stdout.strip().split(",")
    w, h = int(info[0]), int(info[1])
    sh = max(2, round(h * W / w / 2) * 2)
    raw = subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-c:v", "libvpx-vp9", "-i", str(path), "-vf", f"scale={W}:{sh}", "-f", "rawvideo", "-pix_fmt", "rgba", "-"],
                         capture_output=True, check=True).stdout
    n = len(raw) // (W * sh * 4)
    size = W * sh * 4
    return [raw[i * size:(i + 1) * size] for i in range(n)]


def diff(a: bytes, b: bytes):
    return sum(abs(x - y) for x, y in zip(a, b)) / len(a)


def analyse(fr):
    n = len(fr)
    last = fr[-1]
    motion = statistics.median(diff(fr[i], fr[i + 1]) for i in range(n - 1))
    cand = range(n // 2, n - 8)         # the intro is the first half at most; the loop must leave at least 8 frames
    dist = {i: diff(last, fr[i]) for i in cand}
    first = diff(last, fr[0])
    best = min(dist, key=dist.get) if dist else 0
    # frame `best` follows the last frame when looping, so the seam is last -> best; a whole-clip loop is last -> 0
    # a whole-clip loop (start 0) unless its seam is clearly rougher than the clip's own motion and another frame joins much better
    rough = first > 1.5 * motion + 0.3
    start, seam = (best, dist[best]) if rough and dist[best] < first * 0.6 else (0, first)
    return {"bestAlt": [best, round(dist[best], 3)], "frames": n, "loopStart": start, "seam": round(seam, 3), "firstSeam": round(first, 3), "motion": round(motion, 3)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--paperdoll", default=str(HOME / "out" / "paperdoll"))
    ap.add_argument("--out", default=str(ROOT / "data" / "ripperdoc" / "loops.json"))
    a = ap.parse_args(argv)
    layout = json.loads((ROOT / "data" / "ripperdoc" / "layout.json").read_text())
    res = {}
    for gender, g in sorted(layout["genders"].items()):
        for key, z in sorted(g["zones"].items()):
            name = z["clip"]["name"]
            p = Path(a.paperdoll) / gender / f"{name}_sm.webm"
            if not p.is_file():
                print(f"missing {p}", file=sys.stderr)
                continue
            r = analyse(frames(p))
            r["fps"] = 30
            res[f"{gender}/{name}"] = r
            print(f"{gender}/{name:24s} frames {r['frames']:3d} loop from {r['loopStart']:3d}  seam {r['seam']:6.2f}  (to frame 0: {r['firstSeam']:6.2f}, neighbour motion {r['motion']:5.2f})")
    Path(a.out).write_text(json.dumps({"_note": "Generated by tools/loop_points.py. loopStart = frame the clip jumps back to after its last frame (0 = native loop).", "clips": res}, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
