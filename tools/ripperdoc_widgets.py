#!/usr/bin/env python3
"""Generate data/ripperdoc/widgets.json: numbers for the game's slot tile (slots.inkwidget `itemDisplay`), item tooltip
(itemtooltip.inkwidget) and capacity segment, plus the atlas parts they use (Python 3 stdlib only).

  tools/ripperdoc_widgets.py

Reads ~/work/cyber-art/raw/ui (read only; raw game content, never committed) through tools/ripperdoc_data.py and writes only numbers
and part names, on the 1920x1080 stage (the 3840x2160 design grid halved). docs/RIPPERDOC-SPEC.md section 10 is generated from the same
reader by tools/ripperdoc_spec.py. Deterministic: same input, same output.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ripperdoc_data as rd  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
H = 0.5
SLOTS = f"{rd.COMMON}/components/slots.inkwidget.json"
TIP = f"{rd.COMMON}/tooltip/itemtooltip.inkwidget.json"
ANIM = f"{rd.COMMON}/components/slots_animations.inkanim.json"


def flat(root):
    out = []
    rd.walk(root, lambda n, d: out.append(n))
    return out


def named(root, *names):
    """First node of each name (searching the whole item tree), as {name: node}."""
    found = {}
    for n in flat(root):
        if n["name"] in names and n["name"] not in found:
            found[n["name"]] = n
    missing = [x for x in names if x not in found]
    if missing:
        sys.exit(f"widget nodes not found: {missing}")
    return found


def r(v):
    return round(v * H, 2)


def font(n):
    return r(n["text"]["fontSize"])


def part_key(n):
    return f"{Path(n['atlas']).name.replace('.inkatlas', '')}/{n['part']}"


def sequences():
    out = {}
    for s in rd.animations(ANIM):
        out[s["name"]] = s
    return out


def pulses(seq, which=0):
    """The flicker of Item_Hover_In: (count, step, duration) from the first targeted widget's alternating Transparency 1<->0 keys."""
    d = seq["defs"][which]["interpolators"]
    return {"count": len(d), "step": round(d[1]["delay"] - d[0]["delay"], 4), "dur": d[0]["duration"], "total": round(d[-1]["delay"] + d[-1]["duration"], 4)}


def build():
    lib = rd.widget_library(SLOTS)
    tip = rd.widget_library(TIP)
    disp = lib["itemDisplay"]["root"]
    n = named(disp, "container", "rarityContainer", "accent", "itemIcon", "itemEmptyIcon", "lockedIcon", "equippedMarker", "selectedFrame", "selectedFrame2",
              "backgroundEquippedFrame", "itemWrapper")
    cell = [n["container"]["size"][0], n["container"]["size"][1]]
    seqs = sequences()
    sel = seqs["CW_selected_slot"]["defs"][0]["interpolators"]
    hov = pulses(seqs["Item_Hover_In"])
    ttip = tip["itemTooltip"]["root"]
    head = tip["itemHeader"]["root"]
    cap = tip["itemCapacityStat"]["root"]
    stat = tip["itemDetailsStat"]["root"]
    bottom = tip["itemBottom"]["root"]
    t = named(ttip, "contentWrapper", "minWidth", "categoriesWrapper")
    h = named(head, "nameLabel", "separator", "rarityLabel", "itemTypeLabel", "wrapper")
    c = named(cap, "value", "ripperdocIcon", "allocatios")
    s = named(stat, "value", "name", "comparedValue", "arrow")
    b = named(bottom, "value")
    parts = sorted({part_key(x) for x in flat(disp) if x.get("part") and x["name"] in (
        "background", "frame", "accent", "emptyItemLines", "itemEmptyIcon", "lockedIcon", "equippedMarker", "selectedFrame", "selectedFrame2",
        "backgroundHover", "backgroundEquipped", "frameEquipped", "backgroundEquippedFrame", "backgroundIconic")} | {
        "atlas_shapes_sync/unified_tooltip_fill", "atlas_shapes_sync/unified_tooltip_stroke", "atlas_shapes_sync/unified_tooltip_outline",
        "atlas_shapes_sync/label_frame", "atlas_shapes_sync/label_frame_line", "atlas_common/icon_compare_small", "mappin_icons/ripperdoc",
        "atlas_common/ico_lock", "inventory4_atlas/icon_add"})
    # parts the game uses that this export does not contain (atlas_inventory.inkatlas, fullscreen_elements.inkatlas): reported, not guessed
    absent = sorted(p for p in parts if p.startswith(("atlas_inventory/", "fullscreen_elements/", "cyberware_pop_up_temp/", "new_phone_assets/", "hub_atlas/")))
    parts = [p for p in parts if p not in absent]
    return {
        "_note": "Generated by tools/ripperdoc_widgets.py from the game's slot and tooltip widgets (numbers on the 1920x1080 stage = design grid / 2). Do not edit.",
        "cell": {"size": [r(cell[0]), r(cell[1])], "strip": r(n["rarityContainer"]["size"][0]), "padding": r(2), "iconSize": [r(n["itemIcon"]["size"][0]), r(n["itemIcon"]["size"][1])],
                 "lockedMargin": [r(m) for m in n["lockedIcon"]["margin"]], "equippedMarkerMargin": [r(m) for m in n["equippedMarker"]["margin"]],
                 "gridGap": 0},
        "hover": {"flicker": hov, "borderOpacity": {"Default": 0.13, "Hover": 1}, "note": "Item_Hover_In: the icon/mods/ammo content flickers 1->0->1 four times; border opacity 0.13 -> 1 in state Hover"},
        "selected": {"fadeIn": {"dur": sel[0]["duration"], "type": sel[0]["type"], "mode": sel[0]["mode"]},
                     "fadeOut": {"dur": sel[1]["duration"], "delay": sel[1]["delay"], "type": sel[1]["type"], "mode": sel[1]["mode"]},
                     "offset": sel[2]["from"], "frameOpacity": [n["selectedFrame"]["opacity"], n["selectedFrame2"]["opacity"]]},
        "tooltip": {"width": r(t["minWidth"]["size"][0]), "padding": [r(m) for m in t["contentWrapper"]["margin"]], "categories": [r(m) for m in t["categoriesWrapper"]["margin"]],
                    "name": {"font": font(h["nameLabel"]), "margin": [r(m) for m in h["nameLabel"]["margin"]]},
                    "separator": [r(h["separator"]["size"][0]), r(h["separator"]["size"][1])], "wrapperMargin": [r(m) for m in h["wrapper"]["margin"]],
                    "rarity": {"font": font(h["rarityLabel"])}, "type": {"font": font(h["itemTypeLabel"])},
                    "capacity": {"font": font(c["value"]), "icon": [r(c["ripperdocIcon"]["size"][0]), r(c["ripperdocIcon"]["size"][1])], "iconMargin": [r(m) for m in c["ripperdocIcon"]["margin"]]},
                    "stat": {"font": font(s["name"]), "compared": font(s["comparedValue"]), "margin": [r(m) for m in s["name"]["margin"]]},
                    "bottom": {"font": font(b["value"])}},
        "parts": parts,
        "absentParts": absent,
    }


def main():
    out = ROOT / "data" / "ripperdoc"
    out.mkdir(parents=True, exist_ok=True)
    w = build()
    (out / "widgets.json").write_text(json.dumps(w, indent=1) + "\n")
    print(f"widgets: {len(w['parts'])} parts ({len(w['absentParts'])} absent from the export: {', '.join(w['absentParts']) or '-'})")


if __name__ == "__main__":
    main()
